const { contextBridge, ipcRenderer, webUtils } = require('electron');

const on = (ch, cb) => ipcRenderer.on(ch, (_, v) => cb(v));

contextBridge.exposeInMainWorld('api', {
  pickFolder: () => ipcRenderer.invoke('pick-folder'),
  downloadDir: () => ipcRenderer.invoke('download-dir'),
  openDir: (p) => ipcRenderer.invoke('open-dir', p),
  scan: (roots) => ipcRenderer.invoke('scan', roots),
  cover: (file) => ipcRenderer.invoke('cover', file),
  lyrics: (q) => ipcRenderer.invoke('lyrics', q),
  lyricsSearch: (text) => ipcRenderer.invoke('lyrics:search', text),
  lyricsSave: (v) => ipcRenderer.invoke('lyrics:save', v),
  ytSearch: (q) => ipcRenderer.invoke('yt:search', q),
  ytDownload: (v) => ipcRenderer.invoke('yt:download', v),
  ytStatus: () => ipcRenderer.invoke('yt:status'),
  ytCookiesStatus: () => ipcRenderer.invoke('yt:cookies:status'),
  ytCookiesImport: () => ipcRenderer.invoke('yt:cookies:import'),
  ytCookiesRemove: () => ipcRenderer.invoke('yt:cookies:remove'),
  ytUpdate: () => ipcRenderer.invoke('yt:update'),
  onBatch: (cb) => on('scan:batch', cb),
  onYtProgress: (cb) => on('yt:progress', cb),
  onYtStatus: (cb) => on('yt:note', cb),
  appInfo: () => ipcRenderer.invoke('app:info'),
  updCheck: () => ipcRenderer.invoke('upd:check'),
  updInstall: (version) => ipcRenderer.invoke('upd:install', version),
  onUpdProgress: (cb) => on('upd:progress', cb),
  trayState: (s) => ipcRenderer.send('tray:state', s),
  trayConfig: (c) => ipcRenderer.send('tray:config', c),
  onTrayCmd: (cb) => on('tray:cmd', cb),
  trackUpdate: (path, patch) => ipcRenderer.invoke('track:update', path, patch),
  trackDelete: (path) => ipcRenderer.invoke('track:delete', path),
  reveal: (path) => ipcRenderer.invoke('reveal', path),
  openUrl: (url) => ipcRenderer.invoke('open-url', url),
  copyText: (text) => ipcRenderer.invoke('copy-text', text),
  editCmd: (cmd) => ipcRenderer.invoke('edit-cmd', cmd),
  winMin: () => ipcRenderer.send('win:min'),
  winMax: () => ipcRenderer.send('win:max'),
  winClose: () => ipcRenderer.send('win:close'),
  winIsMax: () => ipcRenderer.invoke('win:is-max'),
  onWinState: (cb) => on('win:state', cb),
  onBarState: (cb) => on('bar:state', cb),
  pathOf: (file) => webUtils.getPathForFile(file),
});
